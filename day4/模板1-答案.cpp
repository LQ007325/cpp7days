// ============================================================
// 模板1 改一处：一直读，读到 0 为止（0 不算进去）
// ============================================================
// 跑法：VS Code 里按 Ctrl+Shift+B
//
// 要验证的输入（每个都试一次）：
//   A. 1 2 3 4 5 0      → 读进来 5 个数: 1 2 3 4 5
//   B. 0                → 读进来 0 个数
//   C. 7 0              → 读进来 1 个数: 7
//   D. 5 5 0 9 9 0      → 读进来 2 个数: 5 5   （遇到第一个 0 就停）
//   E. 1 2 3            → 读进来 3 个数: 1 2 3  （没有 0 结尾！别忘了测这个）
// ============================================================
//
// ⭐ 你可以写两版，都跑一遍，比较差别：
//
//   版本一（你写的那种，分四步走）：
//       cin >> x;
//       while (x != 0) {
//           v.push_back(x);
//           cin >> x;
//       }
//
//   版本二（一行写完，推荐）：
//       while (cin >> x && x != 0) {
//           v.push_back(x);
//       }
//
//   两版在 A-D 上都一样。差别在 E：
//      版本一，输入完 "1 2 3" 后 cin 读不到东西了，
//                但 x 还是上一次的值（3），while(3 != 0) 一直成立 → 死循环
//      版本二，cin >> x 读失败返回 false，整行直接停 → 正常结束
//
//   所以版本二更安全。C++ 里 "读到了吗" 这件事本身就是一个值。
// ============================================================

#include <iostream>
#include <vector>
using namespace std;

int main() {
    vector<int> v;
    int x;

    while (cin >> x && x != 0) {   // 读成功 且 不是 0 才进循环体
        v.push_back(x);
    }

    cout << "读进来 " << v.size() << " 个数";
    if (!v.empty()) {
        cout << ": ";
        for (int i = 0; i < (int)v.size(); i++) {
            cout << v[i] << " ";
        }
    }
    cout << endl;

    return 0;
}
